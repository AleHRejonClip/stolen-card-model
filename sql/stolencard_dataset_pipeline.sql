        CASE WHEN nvl(t.blacklist_stolencard_label, 0) = 1 OR nvl(t.blacklist_ato_label, 0) = 1 OR nvl(t.blacklist_suspicious_highsev_label, 0) = 1 THEN 1 ELSE 0 END AS blacklist_label,
