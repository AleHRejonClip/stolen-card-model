    nvl(dc.running_disputes_amount, 0) AS running_disputes_amount,
    CASE WHEN nvl(dc.running_disputes_amount, 0)/cc.running_total_amount > 0.1 THEN 1 ELSE 0 END AS dispute_by_amount_greater10p,
    nvl(d.controversy_type_dispute, 0) AS controversy_type_dispute,
    nvl(d.controversy_type_chargeback, 0) AS controversy_type_chargeback,
    CASE WHEN cs.cs_userid = 1 THEN 1 ELSE 0 END AS blacklist_stolencard_label,
    CASE WHEN cs.ato_userid = 1 THEN 1 ELSE 0 END AS blacklist_ato_label,
    CASE WHEN s.suspicious_userid = 1 AND t.transaction_amount > 2000 THEN 1 ELSE 0 END AS blacklist_suspicious_highsev_label
    FROM card_transactions_dedup t
    LEFT JOIN card_cumamount_dedup cc
    ON t.user_id = cc.user_id AND t.trans_id = cc.trans_id
    LEFT JOIN dispute_cases d
    ON t.user_id = d.user_id AND t.trans_id = d.trans_id
    LEFT JOIN disputes_cumamount dc
    ON t.user_id = dc.user_id AND t.trans_id = dc.trans_id
    LEFT JOIN suspicious_user s
    ON t.user_id = s.user_id AND t.transaction_timestamp > s.blacklist_time
    LEFT JOIN cs_ato_user cs
    ON t.user_id = cs.user_id AND t.transaction_timestamp > cs.blacklist_time
),

disputes_amt_gt_10p AS (
    SELECT
        user_id,
        MAX(dispute_by_amount_greater10p) AS disputes_amt_gt_10p_label
    FROM txns_disputes_blacklist
    GROUP BY user_id
),

